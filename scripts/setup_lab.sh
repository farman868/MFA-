#!/usr/bin/env bash
# One-shot provisioning for the enterprise MFA lab.
#   1. preflight checks          2. generate lab/.env (random secrets) if missing
#   3. validate + build + start  4. wait for health checks
#   5. Keycloak post-import config via kcadm.sh (flow binding, LDAP full sync)
#   6. enable Wazuh log ingestion 7. run scripts/verify_mfa.py
# Usage: scripts/setup_lab.sh [--no-verify] [--skip-build]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LAB="$ROOT/lab"
ENV_FILE="$LAB/.env"
REALM=enterprise-realm
VERIFY=1; BUILD=1
for arg in "$@"; do
  case "$arg" in
    --no-verify) VERIFY=0 ;;
    --skip-build) BUILD=0 ;;
    -h|--help) sed -n '2,8p' "$0"; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

log()  { printf '\033[1;34m[setup]\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m[  ok ]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[fail ]\033[0m %s\n' "$*" >&2; exit 1; }
dc()   { docker compose --project-directory "$LAB" -f "$LAB/docker-compose.yml" "$@"; }

# ------------------------------------------------------------------ 1. preflight
command -v docker >/dev/null || die "docker is not installed"
docker compose version >/dev/null 2>&1 || die "docker compose v2 plugin is required"
docker info >/dev/null 2>&1 || die "docker daemon is not running"
command -v python3 >/dev/null || die "python3 is required on the host (stdlib only)"
[ -e /dev/net/tun ] || log "warning: /dev/net/tun not visible on this host; Docker Desktop provides it inside its VM"

# ------------------------------------------------------------------ 2. secrets
if [ ! -f "$ENV_FILE" ]; then
  log "generating $ENV_FILE with random lab secrets"
  python3 - "$ENV_FILE" <<'PY'
import secrets, string, sys
alnum = string.ascii_letters + string.digits
def pw(n=24): return "".join(secrets.choice(alnum) for _ in range(n))
values = {
  "LDAP_ADMIN_PASSWORD": pw(), "LDAP_CONFIG_PASSWORD": pw(), "LDAP_READONLY_PASSWORD": pw(),
  "KC_DB_PASSWORD": pw(), "KC_ADMIN_USER": "kcadmin", "KC_ADMIN_PASSWORD": pw(),
  "CORP_PORTAL_CLIENT_SECRET": pw(40), "HR_PORTAL_CLIENT_SECRET": pw(40), "VPN_RADIUS_CLIENT_SECRET": pw(40),
  "BRIDGE_API_KEY": pw(40), "OTP_HMAC_KEY": pw(48), "PORTAL_SESSION_KEY": pw(48),
  "RADIUS_SHARED_SECRET": pw(32), "SVC_PROBE_PASSWORD": "Probe-" + pw(18), "SVC_PROBE_TOTP_SEED": pw(20),
}
with open(sys.argv[1], "w") as f:
    f.write("# Generated by scripts/setup_lab.sh - LAB SECRETS ONLY\n")
    f.writelines(f"{k}={v}\n" for k, v in values.items())
PY
  chmod 600 "$ENV_FILE"
  ok "secrets written (chmod 600)"
else
  ok "using existing $ENV_FILE"
fi
set -a; . "$ENV_FILE"; set +a

# ------------------------------------------------------------------ 3. validate, build, start
log "validating compose file"
dc config -q && ok "docker compose config: valid"
if [ "$BUILD" = 1 ]; then
  log "building images (first run downloads Maven/Keycloak/Python layers; allow several minutes)"
  dc build
fi
log "starting the lab"
dc up -d

# ------------------------------------------------------------------ 4. health
wait_healthy() {
  local svc="$1" timeout="${2:-300}" mode="${3:-hard}" start cid status
  start=$(date +%s)
  while :; do
    cid=$(dc ps -q "$svc" 2>/dev/null || true)
    status=$( [ -n "$cid" ] && docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$cid" 2>/dev/null || echo "missing")
    case "$status" in
      healthy|running) ok "$svc is $status"; return 0 ;;
    esac
    if (( $(date +%s) - start > timeout )); then
      dc logs --tail=60 "$svc" >&2 || true
      [ "$mode" = soft ] && { log "warning: $svc not healthy after ${timeout}s (status: $status)"; return 1; }
      die "$svc did not become healthy within ${timeout}s (status: $status)"
    fi
    sleep 5
  done
}
for svc in openldap postgres mailpit mfa-otp-bridge; do wait_healthy "$svc" 180; done
wait_healthy keycloak 420
for svc in corp-portal hr-portal freeradius openvpn; do wait_healthy "$svc" 180; done

# ------------------------------------------------------------------ 5. Keycloak post-import configuration
KCADM=(dc exec -T keycloak /opt/keycloak/bin/kcadm.sh)
KCCFG=(--config /tmp/kcadm.config)
log "logging in to Keycloak admin CLI"
"${KCADM[@]}" config credentials "${KCCFG[@]}" --server http://localhost:8080 --realm master \
  --user "${KC_ADMIN_USER:-kcadmin}" --password "$KC_ADMIN_PASSWORD" >/dev/null
ok "kcadm authenticated"

log "binding enterprise-browser flow and confirming realm security settings"
"${KCADM[@]}" update "realms/$REALM" "${KCCFG[@]}" -s browserFlow=enterprise-browser \
  -s bruteForceProtected=true -s eventsEnabled=true -s adminEventsEnabled=true
ok "browser flow = enterprise-browser, brute-force protection on, events on"

log "enabling backup codes (Recovery Authentication Codes required action)"
if ! "${KCADM[@]}" get "authentication/required-actions/CONFIGURE_RECOVERY_AUTHN_CODES" -r "$REALM" "${KCCFG[@]}" >/dev/null 2>&1; then
  "${KCADM[@]}" create authentication/register-required-action -r "$REALM" "${KCCFG[@]}" \
    -s providerId=CONFIGURE_RECOVERY_AUTHN_CODES -s name="Recovery Authentication Codes" -s defaultAction=false </dev/null || true
fi
"${KCADM[@]}" update "authentication/required-actions/CONFIGURE_RECOVERY_AUTHN_CODES" -r "$REALM" "${KCCFG[@]}" \
  -s enabled=true -s defaultAction=false </dev/null && ok "backup codes available in the account console" || log "warning: could not enable backup codes"

log "triggering LDAP full sync (corp-ldap -> Keycloak)"
"${KCADM[@]}" create "user-storage/corp-ldap/sync?action=triggerFullSync" -r "$REALM" "${KCCFG[@]}" </dev/null
USER_COUNT=$("${KCADM[@]}" get users -r "$REALM" "${KCCFG[@]}" --fields username -q max=100 | grep -c '"username"' || true)
ok "realm $REALM now has $USER_COUNT users (10 LDAP + 1 local probe expected)"

# ------------------------------------------------------------------ 6. SIEM
# Wazuh is in the compose stack (not on the host). A SIEM problem must not abort provisioning:
# the monitoring checks in verify_mfa.py report it instead.
if wait_healthy wazuh-manager 420 soft; then
  "$ROOT/scripts/wazuh_enable_ingestion.sh" || log "warning: Wazuh ingestion setup failed (see output above)"
fi

cat <<INFO

  Lab is up.
    Corp Portal (SSO app)   http://localhost:5000      (legacy single-factor baseline: /legacy)
    HR Self-Service (SSO)   http://localhost:5001
    Keycloak admin console  http://localhost:8080/admin   user: ${KC_ADMIN_USER:-kcadmin}  (password in lab/.env)
    Account console (MFA)   http://localhost:8080/realms/$REALM/account
    Mailpit (Email OTP)     http://localhost:8025
    Mock SMS handset        http://localhost:8000/sms/inbox
    LDAP test password      Corp!Lab2026   (all 10 directory users, e.g. m.rao, j.doe, r.iyer)

  Next: scripts/run_all.sh runs the baseline assessment, verification, IR drill and usage report.

INFO

# ------------------------------------------------------------------ 7. verification
if [ "$VERIFY" = 1 ]; then
  python3 "$ROOT/scripts/verify_mfa.py"
fi

